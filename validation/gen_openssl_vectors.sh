#!/usr/bin/env bash
# Regenerates shawncore-pq-crypto/tests/vectors/openssl_interop.txt with OpenSSL >= 3.5.
#
# OpenSSL's ML-KEM-1024 and ML-DSA-87 are an implementation independent of the
# `ml-kem`/`ml-dsa` crates. Every value below is produced by OpenSSL from fixed seeds;
# nothing is computed by ShawnCore. These are cross-implementation vectors, not NIST ACVP.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${SHAWNCORE_VECTOR_OUT:-$ROOT/shawncore-pq-crypto/tests/vectors/openssl_interop.txt}"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
cd "$TMP"

VERSION="$(openssl version | awk '{print $2}')"
case "$VERSION" in
    3.[5-9]*|[4-9].*) ;;
    *) printf '%s\n' "OpenSSL >= 3.5 is required (found $VERSION)" >&2; exit 1 ;;
esac

hex() { python3 -c 'import sys; print(open(sys.argv[1],"rb").read().hex())' "$1"; }
seq_hex() { python3 -c 'import sys; a,b,n=map(int,sys.argv[1:]); print(bytes((a+i*b)%256 for i in range(n)).hex())' "$@"; }

{
    printf '%s\n' "# Generated by validation/gen_openssl_vectors.sh with OpenSSL $VERSION."
    printf '%s\n' "# Cross-implementation vectors from an independent ML-KEM/ML-DSA implementation; not NIST ACVP."

    for index in 1 2; do
        if [[ $index == 1 ]]; then seed="$(seq_hex 0 1 64)"; ikme="$(seq_hex 100 1 32)"
        else seed="$(seq_hex 7 13 64)"; ikme="$(seq_hex 200 3 32)"; fi

        openssl genpkey -algorithm ML-KEM-1024 -pkeyopt "hexseed:$seed" -out "k$index.pem"
        openssl pkey -in "k$index.pem" -pubout -out "k$index.pub.pem"
        openssl pkey -in "k$index.pub.pem" -pubin -outform DER -out "k$index.pub.der"
        tail -c 1568 "k$index.pub.der" > "k$index.pk"
        openssl pkeyutl -encap -pubin -inkey "k$index.pub.pem" -pkeyopt "hexikme:$ikme" \
            -out "k$index.ct" -secret "k$index.ss"
        python3 - "k$index.ct" "k$index.bad" <<'PY'
import sys
data = bytearray(open(sys.argv[1], "rb").read())
data[0] ^= 1
open(sys.argv[2], "wb").write(data)
PY
        openssl pkeyutl -decap -inkey "k$index.pem" -in "k$index.bad" -secret "k$index.badss"

        printf 'kem%s.seed = %s\n' "$index" "$seed"
        printf 'kem%s.pk = %s\n' "$index" "$(hex "k$index.pk")"
        printf 'kem%s.m = %s\n' "$index" "$ikme"
        printf 'kem%s.ct = %s\n' "$index" "$(hex "k$index.ct")"
        printf 'kem%s.ss = %s\n' "$index" "$(hex "k$index.ss")"
        printf 'kem%s.tampered_ct = %s\n' "$index" "$(hex "k$index.bad")"
        printf 'kem%s.tampered_ss = %s\n' "$index" "$(hex "k$index.badss")"
    done

    seed="$(seq_hex 0 1 32)"
    openssl genpkey -algorithm ML-DSA-87 -pkeyopt "hexseed:$seed" -out d.pem
    openssl pkey -in d.pem -pubout -out d.pub.pem
    openssl pkey -in d.pub.pem -pubin -outform DER -out d.pub.der
    tail -c 2592 d.pub.der > d.pk
    printf 'ShawnCore interop message' > msg.bin
    openssl pkeyutl -sign -inkey d.pem -rawin -in msg.bin -pkeyopt deterministic:1 -out d.sig
    openssl pkeyutl -verify -pubin -inkey d.pub.pem -rawin -in msg.bin -sigfile d.sig >/dev/null

    printf 'dsa.seed = %s\n' "$seed"
    printf 'dsa.pk = %s\n' "$(hex d.pk)"
    printf 'dsa.msg = %s\n' "$(hex msg.bin)"
    printf 'dsa.sig = %s\n' "$(hex d.sig)"

    # A full session (ML-KEM via OpenSSL, everything else re-derived in Python), see the script.
    python3 "$ROOT/validation/gen_session_vector.py"
} > "$OUT.new"

mv "$OUT.new" "$OUT"
printf '%s\n' "wrote $OUT"
