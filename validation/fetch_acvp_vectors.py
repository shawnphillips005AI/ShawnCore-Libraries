#!/usr/bin/env python3
"""Fetches the official NIST ACVP-Server vectors used by tests/acvp_kat.rs.

Only ML-KEM-1024 (FIPS 203) and ML-DSA-87 (FIPS 204) cases are kept. Values are copied
verbatim from usnistgov/ACVP-Server at a pinned commit; nothing is computed locally except
the file SHA-256 recorded in the header. Needs network access and is NOT part of the release
gate: the committed output is the artifact the tests read.

    python3 validation/fetch_acvp_vectors.py [COMMIT]
"""
import hashlib
import json
import sys
import urllib.request

REPO = "usnistgov/ACVP-Server"
BASE = "gen-val/json-files"
OUT = "shawncore-pq-crypto/tests/vectors/acvp_fips203_204.txt"


def get(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=120) as response:
        return response.read()


def main() -> None:
    commit = sys.argv[1] if len(sys.argv) > 1 else json.loads(
        get(f"https://api.github.com/repos/{REPO}/commits/master"))["sha"]

    def fetch(directory: str, name: str):
        raw = get(f"https://raw.githubusercontent.com/{REPO}/{commit}/{BASE}/{directory}/{name}.json")
        return json.loads(raw), hashlib.sha256(raw).hexdigest()

    lines = [
        f"# Official NIST ACVP-Server vectors, {REPO} commit {commit}.",
        "# Generated by validation/fetch_acvp_vectors.py. Values are verbatim; booleans are 01/00.",
    ]

    def emit(prefix, tc_id, **fields):
        for name, value in fields.items():
            if isinstance(value, bool):
                value = "01" if value else "00"
            lines.append(f"{prefix}.{tc_id}.{name} = {value.lower()}")

    def group(prompt, expected, **match):
        for g in prompt["testGroups"]:
            if all(g.get(k) == v for k, v in match.items()):
                results = {}
                for eg in expected["testGroups"]:
                    if eg["tgId"] == g["tgId"]:
                        results = {t["tcId"]: t for t in eg["tests"]}
                return g, results
        raise SystemExit(f"group not found: {match}")

    sources = []

    def load(directory):
        prompt, p_hash = fetch(directory, "prompt")
        expected, e_hash = fetch(directory, "expectedResults")
        sources.append(f"# {directory}: vsId {prompt['vsId']} prompt sha256 {p_hash} expectedResults sha256 {e_hash}")
        return prompt, expected

    prompt, expected = load("ML-KEM-keyGen-FIPS203")
    g, res = group(prompt, expected, parameterSet="ML-KEM-1024")
    for t in g["tests"]:
        emit("mlkem.keygen", t["tcId"], d=t["d"], z=t["z"], ek=res[t["tcId"]]["ek"], dk=res[t["tcId"]]["dk"])

    prompt, expected = load("ML-KEM-encapDecap-FIPS203")
    g, res = group(prompt, expected, parameterSet="ML-KEM-1024", function="encapsulation")
    for t in g["tests"]:
        emit("mlkem.encap", t["tcId"], ek=t["ek"], m=t["m"], c=res[t["tcId"]]["c"], k=res[t["tcId"]]["k"])
    g, res = group(prompt, expected, parameterSet="ML-KEM-1024", function="decapsulation")
    for t in g["tests"]:
        emit("mlkem.decap", t["tcId"], dk=t["dk"], c=t["c"], k=res[t["tcId"]]["k"])
    g, res = group(prompt, expected, parameterSet="ML-KEM-1024", function="encapsulationKeyCheck")
    for t in g["tests"]:
        emit("mlkem.ekcheck", t["tcId"], ek=t["ek"], passed=res[t["tcId"]]["testPassed"])
    g, res = group(prompt, expected, parameterSet="ML-KEM-1024", function="decapsulationKeyCheck")
    for t in g["tests"]:
        emit("mlkem.dkcheck", t["tcId"], dk=t["dk"], passed=res[t["tcId"]]["testPassed"])

    prompt, expected = load("ML-DSA-keyGen-FIPS204")
    g, res = group(prompt, expected, parameterSet="ML-DSA-87")
    for t in g["tests"]:
        emit("mldsa.keygen", t["tcId"], seed=t["seed"], pk=res[t["tcId"]]["pk"])

    prompt, expected = load("ML-DSA-sigVer-FIPS204")
    g, res = group(prompt, expected, parameterSet="ML-DSA-87", signatureInterface="external", preHash="pure")
    for t in g["tests"]:
        emit("mldsa.sigver", t["tcId"], pk=t["pk"], message=t["message"], context=t["context"],
             signature=t["signature"], passed=res[t["tcId"]]["testPassed"])

    lines[2:2] = sources
    with open(OUT, "w") as handle:
        handle.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}: {len(lines)} lines from commit {commit}")


if __name__ == "__main__":
    main()
